//! Core code generation: Lexicon types -> Rust source.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use proto_blue_lexicon::types::{
    LexObject, LexRefUnion, LexUserType, LexXrpcError, LexXrpcParameters, LexXrpcProcedure,
    LexXrpcQuery, LexXrpcSubscription, LexiconDoc,
};

/// Code generator that converts Lexicon documents to Rust source files.
pub struct Generator<'a> {
    docs: &'a [LexiconDoc],
}

impl<'a> Generator<'a> {
    pub const fn new(docs: &'a [LexiconDoc]) -> Self {
        Generator { docs }
    }

    /// Generate all Rust source files. Returns a map of relative path -> content.
    pub fn generate(&self) -> BTreeMap<String, String> {
        let mut files = BTreeMap::new();

        // Track module tree for mod.rs generation
        // Key: directory path, Value: set of child module names
        let mut mod_tree: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();

        // PASS 1 — build the full mod_tree first so PASS 2 can decide
        // per-doc whether an NSID is both a leaf AND a parent. The
        // leaf-and-parent case occurs in the wild (e.g. third-party
        // lexicons that publish `com.example.foo` AND
        // `com.example.foo.bar`) and was the cause of #23 (E0761:
        // ambiguous module file at `<name>.rs` + `<name>/mod.rs`).
        for doc in self.docs {
            let nsid = &doc.id;
            let parts: Vec<&str> = nsid.split('.').collect();
            if parts.len() < 2 {
                continue;
            }
            for i in 0..parts.len() {
                let dir = if i == 0 {
                    String::new()
                } else {
                    parts[..i].join("/")
                };
                let child = parts[i];
                mod_tree.entry(dir).or_default().insert(child.to_string());
            }
        }

        // PASS 2 — emit each lexicon's generated file. When the NSID is
        // ALSO a parent in `mod_tree` (has child NSIDs), write to
        // `<path>/mod.rs` instead of `<path>.rs`; PASS 3 will append the
        // mod-tree directives for the children to the same file.
        for doc in self.docs {
            let nsid = &doc.id;
            let parts: Vec<&str> = nsid.split('.').collect();
            if parts.len() < 2 {
                continue;
            }
            let dir_path = parts.join("/");
            let is_branch = mod_tree.contains_key(&dir_path);
            let file_path = if is_branch {
                format!("{dir_path}/mod.rs")
            } else {
                format!("{dir_path}.rs")
            };
            let content = Self::generate_file(doc);
            files.insert(file_path, content);
        }

        // PASS 3 — emit a `mod.rs` per directory in `mod_tree`, declaring
        // each child module. If a leaf-and-parent already wrote content
        // to `<dir>/mod.rs` in PASS 2 we APPEND the directives below it
        // rather than overwrite (the leaf's defs and the children's
        // sub-modules coexist in one `mod.rs`).
        //
        // Leaf children whose NSID segment differs from its snake-case
        // form (e.g. `getSession`) get a `#[path = "<orig>.rs"]` attribute
        // so the on-disk filename stays NSID-canonical while the Rust
        // module name is clean. Same applies to non-leaf segments
        // containing dashes (e.g. `bad-example`) — see #24, where the
        // missing path attribute on dirs caused E0583.
        for (dir, children) in &mod_tree {
            let mod_path = if dir.is_empty() {
                "mod.rs".to_string()
            } else {
                format!("{dir}/mod.rs")
            };
            let existing = files.get(&mod_path).cloned();
            let mut mod_content = String::new();
            if existing.is_none() {
                mod_content.push_str("// Generated by atproto-codegen. Do not edit.\n");
                // Pedantic+nursery lints are advisory for codegen output —
                // the generator can't audit every cast/doc/struct it emits.
                // Hand-written sites keep the default lint floor; suppress
                // only what would otherwise drown out real signal.
                mod_content
                    .push_str("#![allow(clippy::pedantic, clippy::nursery, clippy::all)]\n\n");
            }

            let mut child_list: Vec<&String> = children.iter().collect();
            child_list.sort();

            for child in child_list {
                let is_leaf = !mod_tree.contains_key(&join_dir(dir, child));
                let snake = to_snake_case(child);
                let rust_ident = sanitize_ident(&snake);
                let needs_path_attr = snake != *child;
                if needs_path_attr {
                    // Disk path uses the original NSID segment; Rust
                    // module name uses the snake form. The suffix
                    // distinguishes leaf .rs from branch /mod.rs.
                    let suffix = if is_leaf { ".rs" } else { "/mod.rs" };
                    writeln!(
                        mod_content,
                        "#[path = \"{child}{suffix}\"]\npub mod {rust_ident};"
                    )
                    .expect("infallible write to String");
                } else {
                    writeln!(mod_content, "pub mod {rust_ident};")
                        .expect("infallible write to String");
                }
            }

            // Append below the leaf's content, or take over a fresh mod.rs.
            if let Some(existing_content) = existing {
                files.insert(mod_path, format!("{existing_content}\n{mod_content}"));
            } else {
                files.insert(mod_path, mod_content);
            }
        }

        files
    }

    /// Generate a single Rust source file for a lexicon document.
    ///
    /// The serde import is emitted conditionally: lexicon documents
    /// that only produce free functions (e.g. `call()` wrappers
    /// without an `Output` struct) don't derive `Deserialize` /
    /// `Serialize` and would leave the `use` dangling as a warning.
    fn generate_file(doc: &LexiconDoc) -> String {
        let nsid = &doc.id;

        // Render defs into a scratch buffer first so we can decide
        // whether the serde import is needed based on the real output.
        let mut body = String::new();
        let mut def_names: Vec<&String> = doc.defs.keys().collect();
        def_names.sort();
        for def_name in def_names {
            let def = &doc.defs[def_name];
            Self::generate_def(&mut body, nsid, def_name, def);
        }

        let mut out = String::new();
        out.push_str("// Generated by atproto-codegen. Do not edit.\n");
        writeln!(out, "//! Lexicon: {nsid}").expect("infallible write to String");
        // Pedantic+nursery lints are advisory for codegen output — the
        // generator can't audit every cast/doc/struct it emits. Hand-
        // written sites keep the default lint floor; suppress only what
        // would otherwise drown out real signal in pedantic sweeps.
        out.push_str("#![allow(clippy::pedantic, clippy::nursery, clippy::all)]\n\n");
        if body.contains("Deserialize") || body.contains("Serialize") {
            out.push_str("use serde::{Deserialize, Serialize};\n\n");
        }
        out.push_str(&body);

        out
    }

    /// Generate Rust code for a single definition.
    fn generate_def(out: &mut String, nsid: &str, def_name: &str, def: &LexUserType) {
        let type_name = def_name_to_type(def_name);

        match def {
            LexUserType::Record(rec) => {
                Self::generate_object(out, nsid, &type_name, &rec.record, true);
            }
            LexUserType::Object(obj) => {
                Self::generate_object(out, nsid, &type_name, obj, false);
            }
            LexUserType::Query(query) => {
                Self::generate_query(out, nsid, &type_name, query);
            }
            LexUserType::Procedure(proc) => {
                Self::generate_procedure(out, nsid, &type_name, proc);
            }
            LexUserType::Subscription(sub) => {
                Self::generate_subscription(out, nsid, &type_name, sub);
            }
            LexUserType::Array(arr) => {
                // Top-level array definitions get a type alias
                let inner = Self::type_to_rust(nsid, &arr.items);
                if let Some(desc) = &arr.description {
                    writeln!(out, "/// {}", escape_doc_text(desc))
                        .expect("infallible write to String");
                }
                writeln!(out, "pub type {type_name} = Vec<{inner}>;")
                    .expect("infallible write to String");
                out.push('\n');
            }
            LexUserType::String(s) => {
                if let Some(enum_values) = &s.enum_values {
                    Self::generate_string_enum(
                        out,
                        &type_name,
                        enum_values,
                        s.description.as_deref(),
                    );
                } else if let Some(known_values) = &s.known_values {
                    Self::generate_known_values(
                        out,
                        &type_name,
                        known_values,
                        s.description.as_deref(),
                    );
                }
                // Plain strings don't need a type alias
            }
            LexUserType::Token(t) => {
                if let Some(desc) = &t.description {
                    writeln!(out, "/// {}", escape_doc_text(desc))
                        .expect("infallible write to String");
                }
                writeln!(
                    out,
                    "pub const {}: &str = \"{nsid}#{def_name}\";",
                    to_screaming_snake(&type_name)
                )
                .expect("infallible write to String");
                out.push('\n');
            }
            LexUserType::Union(union_def) => {
                Self::generate_union(out, nsid, &type_name, union_def);
            }
            // Other types don't generate standalone definitions
            _ => {}
        }
    }

    /// Generate a Rust struct for a Lexicon object.
    fn generate_object(
        out: &mut String,
        nsid: &str,
        type_name: &str,
        obj: &LexObject,
        is_record: bool,
    ) {
        // Aux-type buffer for synthesised inline unions. Inline unions
        // appear as struct properties whose type is `LexUserType::Union`
        // (or arrays thereof); they need a named sibling enum so the
        // struct field's type isn't a bare `serde_json::Value`. We
        // collect those defs here and emit them BEFORE the struct so
        // the struct can reference them by name.
        let mut aux_types = String::new();
        let mut struct_body = String::new();

        // Sort properties for deterministic output
        let mut prop_names: Vec<&String> = obj.properties.keys().collect();
        prop_names.sort();

        let required: BTreeSet<&str> = obj.required.iter().map(String::as_str).collect();
        let nullable: BTreeSet<&str> = obj.nullable.iter().map(String::as_str).collect();
        let mut seen_idents: std::collections::HashSet<String> = std::collections::HashSet::new();
        // Pre-seed with the synthetic `r#type` field that records emit so
        // a real lexicon `type` property doesn't collide with it.
        if is_record {
            seen_idents.insert("r#type".to_string());
        }

        for prop_name in prop_names {
            let prop_type = &obj.properties[prop_name];
            let is_required = required.contains(prop_name.as_str());
            let is_nullable = nullable.contains(prop_name.as_str());

            let raw_rust_name = to_snake_case(prop_name);
            let rust_name = disambiguate(&mut seen_idents, raw_rust_name.clone());
            let was_disambiguated = rust_name != raw_rust_name;

            // Compose a base name hint for any inline union/array-of-union
            // the property's type contains: `<TypeName><PropertyPascalCase>`.
            // The helper appends the right discriminating suffix at the
            // union-emission site (`Refs` for Union, with `Item` inserted
            // before it for `Array<Union>`).
            let union_name_hint = format!("{type_name}{}", to_pascal_case(prop_name));
            let rust_type =
                Self::type_to_rust_with_unions(nsid, prop_type, &mut aux_types, &union_name_hint);

            // Doc-comment the disambiguation so a reader of the generated
            // file can see why the Rust name doesn't match the wire name.
            if was_disambiguated {
                writeln!(
                    struct_body,
                    "    /// Renamed from `{prop_name}` to avoid a Rust identifier collision with a sibling field."
                )
                .expect("infallible write to String");
            }

            // Add serde rename if snake_case differs from camelCase, or if
            // disambiguation produced a name that won't round-trip.
            let needs_rename = rust_name != *prop_name && to_camel_case(&rust_name) != *prop_name;
            if needs_rename {
                writeln!(struct_body, "    #[serde(rename = \"{prop_name}\")]")
                    .expect("infallible write to String");
            }

            if is_required {
                if is_nullable {
                    writeln!(struct_body, "    pub {rust_name}: Option<{rust_type}>,")
                        .expect("infallible write to String");
                } else {
                    writeln!(struct_body, "    pub {rust_name}: {rust_type},")
                        .expect("infallible write to String");
                }
            } else {
                struct_body.push_str("    #[serde(skip_serializing_if = \"Option::is_none\")]\n");
                writeln!(struct_body, "    pub {rust_name}: Option<{rust_type}>,")
                    .expect("infallible write to String");
            }
        }

        // Now emit everything in order: aux types (synthesised unions),
        // then the struct's doc comment + TYPE const + struct itself.
        out.push_str(&aux_types);

        if let Some(desc) = &obj.description
            && !desc.is_empty()
        {
            writeln!(out, "/// {}", escape_doc_text(desc)).expect("infallible write to String");
        }
        // Records carry a `$type` field on the wire — emit a TYPE
        // constant and a serde-serialised `type` field so round-trips
        // preserve the discriminator. Matches TS AtpAgent / codegen.
        if is_record {
            writeln!(
                out,
                "/// `$type` discriminator for this record on the wire.\n\
                 pub const TYPE: &str = \"{nsid}\";"
            )
            .expect("infallible write to String");
            out.push('\n');
        }
        out.push_str("#[derive(Debug, Clone, Serialize, Deserialize)]\n");
        out.push_str("#[serde(rename_all = \"camelCase\")]\n");
        writeln!(out, "pub struct {type_name} {{").expect("infallible write to String");

        if is_record {
            // Serialised as "$type": "<nsid>"; deserialisation preserves
            // whatever was on the wire (including absent, in which case
            // the default is the canonical type string for this NSID).
            out.push_str(
                "    /// The `$type` discriminator. Defaults to [`TYPE`] on construction.\n",
            );
            out.push_str("    #[serde(rename = \"$type\", default = \"default_type\")]\n");
            out.push_str("    pub r#type: String,\n");
        }

        out.push_str(&struct_body);
        out.push_str("}\n\n");

        // Emit the serde `default = "default_type"` helper that the
        // `$type` field uses, so users can deserialise records that
        // omit `$type` without a custom impl.
        if is_record {
            out.push_str("fn default_type() -> String {\n");
            out.push_str("    TYPE.to_string()\n");
            out.push_str("}\n\n");
        }
    }

    /// Variant of `type_to_rust` that materialises inline-union types
    /// instead of falling back to `serde_json::Value`.
    ///
    /// When the type contains a `LexUserType::Union` (directly or nested
    /// inside an `Array`), emits a synthesised sum-type enum into
    /// `aux_out` and returns the synthesised name in place of
    /// `serde_json::Value`. For non-union types, behaves identically to
    /// `type_to_rust`.
    ///
    /// Naming: the caller passes a base `name_hint` unique per
    /// (struct, property) pair (typically `<StructName><PropertyPascalCase>`,
    /// e.g. `MainEmbed`). The helper composes:
    ///   - direct `Union`              → `<name_hint>Refs`         (e.g. `MainEmbedRefs`)
    ///   - `Array<Union>`              → `<name_hint>ItemRefs`     (e.g. `MainFacetsItemRefs`)
    ///   - `Array<Array<Union>>`       → `<name_hint>ItemItemRefs`
    ///
    /// The trailing `Refs` matches the lexicon term (`refs: [...]`) and
    /// guarantees the synthesised name doesn't collide with same-named
    /// top-level defs in the same module — e.g. `app.bsky.embed.record`
    /// defines a `viewRecord` struct (→ `ViewRecord`) and a `view` struct
    /// whose `record` property is a union; without the suffix the
    /// synthesised union would also be `ViewRecord`.
    fn type_to_rust_with_unions(
        nsid: &str,
        ty: &LexUserType,
        aux_out: &mut String,
        name_hint: &str,
    ) -> String {
        match ty {
            LexUserType::Union(union_def) => {
                let synth_name = format!("{name_hint}Refs");
                Self::generate_union(aux_out, nsid, &synth_name, union_def);
                synth_name
            }
            LexUserType::Array(arr) => {
                let inner_hint = format!("{name_hint}Item");
                let inner = Self::type_to_rust_with_unions(nsid, &arr.items, aux_out, &inner_hint);
                format!("Vec<{inner}>")
            }
            // Non-union, non-array: defer to the existing mapping.
            _ => Self::type_to_rust(nsid, ty),
        }
    }

    /// Generate a query (GET endpoint).
    fn generate_query(out: &mut String, nsid: &str, _type_name: &str, query: &LexXrpcQuery) {
        let has_params = query
            .parameters
            .as_ref()
            .is_some_and(|p| !p.properties.is_empty());
        let has_output = query.output.as_ref().is_some_and(|o| o.schema.is_some());

        // Only emit doc comment if we're generating something after it
        if has_params || has_output {
            if let Some(desc) = &query.description {
                writeln!(out, "/// {}", escape_doc_text(desc)).expect("infallible write to String");
            }
            writeln!(out, "/// XRPC Query: {nsid}").expect("infallible write to String");
        }

        if let Some(params) = &query.parameters
            && !params.properties.is_empty()
        {
            Self::generate_params(out, nsid, params);
        }

        if let Some(output) = &query.output
            && let Some(schema) = &output.schema
        {
            Self::generate_body_schema(out, nsid, "Output", schema);
        }

        Self::generate_errors(out, &query.errors);
        Self::generate_query_call_fn(out, nsid, query);
        Self::generate_query_register_fn(out, nsid, query);
    }

    /// Generate a procedure (POST endpoint).
    fn generate_procedure(out: &mut String, nsid: &str, _type_name: &str, proc: &LexXrpcProcedure) {
        let has_params = proc
            .parameters
            .as_ref()
            .is_some_and(|p| !p.properties.is_empty());
        let has_input = proc.input.as_ref().is_some_and(|i| i.schema.is_some());
        let has_output = proc.output.as_ref().is_some_and(|o| o.schema.is_some());

        if has_params || has_input || has_output {
            if let Some(desc) = &proc.description {
                writeln!(out, "/// {}", escape_doc_text(desc)).expect("infallible write to String");
            }
            writeln!(out, "/// XRPC Procedure: {nsid}").expect("infallible write to String");
        }

        if let Some(params) = &proc.parameters
            && !params.properties.is_empty()
        {
            Self::generate_params(out, nsid, params);
        }

        if let Some(input) = &proc.input
            && let Some(schema) = &input.schema
        {
            Self::generate_body_schema(out, nsid, "Input", schema);
        }

        if let Some(output) = &proc.output
            && let Some(schema) = &output.schema
        {
            Self::generate_body_schema(out, nsid, "Output", schema);
        }

        Self::generate_errors(out, &proc.errors);
        Self::generate_procedure_call_fn(out, nsid, proc);
        Self::generate_procedure_register_fn(out, nsid, proc);
    }

    /// Emit a per-method error enum from the `errors` array on the def.
    ///
    /// The enum captures each `def.errors[].name` as a variant so
    /// callers can `match` against well-known codes, with a catch-all
    /// `Xrpc(XrpcError)` for anything the lexicon doesn't enumerate
    /// plus `Fetch`/`Json` transports.
    fn generate_errors(out: &mut String, errors: &[LexXrpcError]) {
        // Always emit the error enum — even when `errors` is empty
        // we want a consistent `CallError` type per method so the
        // `call` signature is uniform.
        out.push_str("/// Errors a `call()` on this method can return.\n");
        out.push_str("#[derive(Debug, thiserror::Error)]\n");
        out.push_str("pub enum CallError {\n");
        for e in errors {
            if let Some(desc) = &e.description {
                let clean = escape_doc_text(&desc.replace('\n', " "));
                writeln!(out, "    /// {clean}").expect("infallible write to String");
            }
            let variant = to_pascal_case(&e.name);
            writeln!(out, "    #[error(\"{}\")]", e.name).expect("infallible write to String");
            writeln!(out, "    {variant},").expect("infallible write to String");
        }
        out.push_str("    #[error(\"{0}\")]\n");
        out.push_str("    Xrpc(proto_blue_xrpc::XrpcError),\n");
        out.push_str("    #[error(transparent)]\n");
        out.push_str("    Transport(#[from] proto_blue_xrpc::Error),\n");
        out.push_str("    #[error(transparent)]\n");
        out.push_str("    Json(#[from] serde_json::Error),\n");
        out.push_str("}\n\n");

        // Mapper from a raw XrpcError to the specific CallError variant
        // when the error `name` matches one of the enumerated codes;
        // otherwise wraps as `CallError::Xrpc(err)`. Emitted as a
        // single `match` on `err.error.as_deref()` to avoid clippy's
        // `single_match` warning when there's only one enumerated
        // variant.
        out.push_str("fn map_xrpc_error(err: proto_blue_xrpc::XrpcError) -> CallError {\n");
        if errors.is_empty() {
            out.push_str("    CallError::Xrpc(err)\n");
        } else {
            out.push_str("    match err.error.as_deref() {\n");
            for e in errors {
                let variant = to_pascal_case(&e.name);
                writeln!(out, "        Some(\"{}\") => CallError::{variant},", e.name)
                    .expect("infallible write to String");
            }
            out.push_str("        _ => CallError::Xrpc(err),\n");
            out.push_str("    }\n");
        }
        out.push_str("}\n\n");
    }

    /// Emit the `call()` helper for a query.
    fn generate_query_call_fn(out: &mut String, nsid: &str, query: &LexXrpcQuery) {
        let has_params = query
            .parameters
            .as_ref()
            .is_some_and(|p| !p.properties.is_empty());
        let has_output = query.output.as_ref().is_some_and(|o| o.schema.is_some());

        // Emit `to_query_params` translator when we have params.
        if has_params && let Some(params) = &query.parameters {
            Self::generate_to_query_params(out, params);
        }

        out.push_str("/// Execute the query.\n");
        out.push_str("pub async fn call(\n");
        out.push_str("    client: &proto_blue_xrpc::XrpcClient,\n");
        if has_params {
            out.push_str("    params: Option<&Params>,\n");
        }
        out.push_str("    opts: Option<&proto_blue_xrpc::CallOptions>,\n");
        if has_output {
            out.push_str(") -> Result<Output, CallError> {\n");
        } else {
            out.push_str(") -> Result<serde_json::Value, CallError> {\n");
        }
        if has_params {
            out.push_str("    let qp = params.map(to_query_params);\n");
            writeln!(
                out,
                "    let response = match client.query(\"{nsid}\", qp.as_ref(), opts).await {{"
            )
            .expect("infallible write to String");
        } else {
            writeln!(
                out,
                "    let response = match client.query(\"{nsid}\", None, opts).await {{"
            )
            .expect("infallible write to String");
        }
        out.push_str("        Ok(r) => r,\n");
        out.push_str(
            "        Err(proto_blue_xrpc::Error::Xrpc(x)) => return Err(map_xrpc_error(x)),\n",
        );
        out.push_str("        Err(e) => return Err(CallError::Transport(e)),\n");
        out.push_str("    };\n");
        if has_output {
            out.push_str("    Ok(serde_json::from_value(response.data)?)\n");
        } else {
            out.push_str("    Ok(response.data)\n");
        }
        out.push_str("}\n\n");
    }

    /// Emit the `call()` helper for a procedure.
    fn generate_procedure_call_fn(out: &mut String, nsid: &str, proc: &LexXrpcProcedure) {
        let has_params = proc
            .parameters
            .as_ref()
            .is_some_and(|p| !p.properties.is_empty());
        let has_input = proc.input.as_ref().is_some_and(|i| i.schema.is_some());
        let has_output = proc.output.as_ref().is_some_and(|o| o.schema.is_some());

        if has_params && let Some(params) = &proc.parameters {
            Self::generate_to_query_params(out, params);
        }

        out.push_str("/// Execute the procedure.\n");
        out.push_str("pub async fn call(\n");
        out.push_str("    client: &proto_blue_xrpc::XrpcClient,\n");
        if has_params {
            out.push_str("    params: Option<&Params>,\n");
        }
        if has_input {
            out.push_str("    input: &Input,\n");
        }
        out.push_str("    opts: Option<&proto_blue_xrpc::CallOptions>,\n");
        if has_output {
            out.push_str(") -> Result<Output, CallError> {\n");
        } else {
            out.push_str(") -> Result<serde_json::Value, CallError> {\n");
        }
        if has_params {
            out.push_str("    let qp = params.map(to_query_params);\n");
            out.push_str("    let qp_ref = qp.as_ref();\n");
        } else {
            out.push_str("    let qp_ref: Option<&proto_blue_xrpc::QueryParams> = None;\n");
        }
        if has_input {
            out.push_str(
                "    let body = proto_blue_xrpc::XrpcBody::Json(serde_json::to_value(input)?);\n",
            );
            writeln!(
                out,
                "    let response = match client.procedure(\"{nsid}\", qp_ref, Some(body), opts).await {{"
            )
            .expect("infallible write to String");
        } else {
            writeln!(
                out,
                "    let response = match client.procedure(\"{nsid}\", qp_ref, None, opts).await {{"
            )
            .expect("infallible write to String");
        }
        out.push_str("        Ok(r) => r,\n");
        out.push_str(
            "        Err(proto_blue_xrpc::Error::Xrpc(x)) => return Err(map_xrpc_error(x)),\n",
        );
        out.push_str("        Err(e) => return Err(CallError::Transport(e)),\n");
        out.push_str("    };\n");
        if has_output {
            out.push_str("    Ok(serde_json::from_value(response.data)?)\n");
        } else {
            out.push_str("    Ok(response.data)\n");
        }
        out.push_str("}\n\n");
    }

    /// Emit the server-side `register()` helper for a query.
    ///
    /// The handler receives typed `Params` (when declared) and
    /// returns `Result<Output, CallError>` (or `Result<JsonValue,
    /// CallError>` when the method has no output schema). The helper
    /// converts the raw `HandlerContext` into typed params and
    /// serialises the output.
    ///
    /// Gated behind the `server` feature so this module compiles
    /// client-side without pulling in axum.
    fn generate_query_register_fn(out: &mut String, nsid: &str, query: &LexXrpcQuery) {
        let has_params = query
            .parameters
            .as_ref()
            .is_some_and(|p| !p.properties.is_empty());
        let has_output = query.output.as_ref().is_some_and(|o| o.schema.is_some());
        out.push_str(
            "/// Register a typed handler for this method on an [`proto_blue_xrpc::XrpcServer`].\n",
        );
        out.push_str("#[cfg(feature = \"server\")]\n");
        out.push_str(
            "pub fn register<F, Fut>(\n\
                 server: proto_blue_xrpc::XrpcServer,\n\
                 handler: F,\n\
             ) -> proto_blue_xrpc::XrpcServer\n",
        );
        out.push_str("where\n");
        if has_params {
            out.push_str("    F: Fn(proto_blue_xrpc::HandlerContext, Option<Params>) -> Fut + Send + Sync + 'static,\n");
        } else {
            out.push_str(
                "    F: Fn(proto_blue_xrpc::HandlerContext) -> Fut + Send + Sync + 'static,\n",
            );
        }
        if has_output {
            out.push_str("    Fut: std::future::Future<Output = Result<Output, proto_blue_xrpc::XrpcServerError>> + Send + 'static,\n");
        } else {
            out.push_str("    Fut: std::future::Future<Output = Result<serde_json::Value, proto_blue_xrpc::XrpcServerError>> + Send + 'static,\n");
        }
        out.push_str("{\n");
        out.push_str("    let handler = std::sync::Arc::new(handler);\n");
        writeln!(out, "    server.query(\"{nsid}\", move |ctx| {{")
            .expect("infallible write to String");
        out.push_str("        let handler = handler.clone();\n");
        out.push_str("        async move {\n");
        if has_params {
            out.push_str("            let params = params_from_ctx(&ctx);\n");
            out.push_str("            let out = handler(ctx, params).await?;\n");
        } else {
            out.push_str("            let out = handler(ctx).await?;\n");
        }
        if has_output {
            out.push_str("            let value = serde_json::to_value(&out)\n");
            out.push_str("                .map_err(|e| proto_blue_xrpc::XrpcServerError::new(proto_blue_xrpc::ResponseType::InternalServerError, format!(\"output serialize: {e}\")))?;\n");
            out.push_str("            Ok::<_, proto_blue_xrpc::XrpcServerError>(value)\n");
        } else {
            out.push_str("            Ok::<_, proto_blue_xrpc::XrpcServerError>(out)\n");
        }
        out.push_str("        }\n");
        out.push_str("    })\n");
        out.push_str("}\n\n");
        if has_params && let Some(params) = &query.parameters {
            Self::generate_params_from_ctx(out, params);
        }
    }

    /// Emit the server-side `register()` helper for a procedure.
    fn generate_procedure_register_fn(out: &mut String, nsid: &str, proc: &LexXrpcProcedure) {
        let has_params = proc
            .parameters
            .as_ref()
            .is_some_and(|p| !p.properties.is_empty());
        let has_input = proc.input.as_ref().is_some_and(|i| i.schema.is_some());
        let has_output = proc.output.as_ref().is_some_and(|o| o.schema.is_some());
        out.push_str("/// Register a typed handler for this procedure on an [`proto_blue_xrpc::XrpcServer`].\n");
        out.push_str("#[cfg(feature = \"server\")]\n");
        out.push_str(
            "pub fn register<F, Fut>(\n\
                 server: proto_blue_xrpc::XrpcServer,\n\
                 handler: F,\n\
             ) -> proto_blue_xrpc::XrpcServer\n",
        );
        out.push_str("where\n");
        let mut arg = String::from("proto_blue_xrpc::HandlerContext");
        if has_params {
            arg.push_str(", Option<Params>");
        }
        if has_input {
            arg.push_str(", Option<Input>");
        }
        writeln!(out, "    F: Fn({arg}) -> Fut + Send + Sync + 'static,")
            .expect("infallible write to String");
        if has_output {
            out.push_str("    Fut: std::future::Future<Output = Result<Output, proto_blue_xrpc::XrpcServerError>> + Send + 'static,\n");
        } else {
            out.push_str("    Fut: std::future::Future<Output = Result<serde_json::Value, proto_blue_xrpc::XrpcServerError>> + Send + 'static,\n");
        }
        out.push_str("{\n");
        out.push_str("    let handler = std::sync::Arc::new(handler);\n");
        writeln!(out, "    server.procedure(\"{nsid}\", move |ctx| {{")
            .expect("infallible write to String");
        out.push_str("        let handler = handler.clone();\n");
        out.push_str("        async move {\n");
        if has_params {
            out.push_str("            let params = params_from_ctx(&ctx);\n");
        }
        if has_input {
            out.push_str("            let input = match ctx.json_body()? {\n");
            out.push_str("                Some(v) => Some(serde_json::from_value::<Input>(v).map_err(|e| proto_blue_xrpc::XrpcServerError::new(proto_blue_xrpc::ResponseType::InvalidRequest, format!(\"input deserialize: {e}\")))?),\n");
            out.push_str("                None => None,\n");
            out.push_str("            };\n");
        }
        // Build the handler call expression based on arg shape.
        let call = match (has_params, has_input) {
            (true, true) => "handler(ctx, params, input)",
            (true, false) => "handler(ctx, params)",
            (false, true) => "handler(ctx, input)",
            (false, false) => "handler(ctx)",
        };
        writeln!(out, "            let out = {call}.await?;").expect("infallible write to String");
        if has_output {
            out.push_str("            let value = serde_json::to_value(&out)\n");
            out.push_str("                .map_err(|e| proto_blue_xrpc::XrpcServerError::new(proto_blue_xrpc::ResponseType::InternalServerError, format!(\"output serialize: {e}\")))?;\n");
            out.push_str("            Ok::<_, proto_blue_xrpc::XrpcServerError>(value)\n");
        } else {
            out.push_str("            Ok::<_, proto_blue_xrpc::XrpcServerError>(out)\n");
        }
        out.push_str("        }\n");
        out.push_str("    })\n");
        out.push_str("}\n\n");
        if has_params && let Some(params) = &proc.parameters {
            Self::generate_params_from_ctx(out, params);
        }
    }

    /// Emit the helper that reads params out of a `HandlerContext`.
    /// Missing values just leave the field `None`; string-based
    /// coercion mirrors the TS `paramsParseLoose` default (numbers
    /// and booleans are accepted in string form, matching how an
    /// HTTP query string transports them).
    fn generate_params_from_ctx(out: &mut String, params: &LexXrpcParameters) {
        out.push_str("#[cfg(feature = \"server\")]\n");
        out.push_str(
            "fn params_from_ctx(ctx: &proto_blue_xrpc::HandlerContext) -> Option<Params> {\n",
        );
        out.push_str("    // Always construct a `Params` — required fields are\n");
        out.push_str("    // validated upstream by the lexicon validator when enabled;\n");
        out.push_str("    // missing values surface as runtime errors from the handler.\n");
        out.push_str("    Some(Params {\n");

        let mut prop_names: Vec<&String> = params.properties.keys().collect();
        prop_names.sort();
        let required: BTreeSet<&str> = params.required.iter().map(String::as_str).collect();

        for prop_name in prop_names {
            let prop = &params.properties[prop_name];
            let field = to_snake_case(prop_name);
            let key = prop_name;
            let is_required = required.contains(prop_name.as_str());

            // `match Some/None` form preferred over `Option::map_or_else`
            // here because the closure-and-default form expands to one
            // unreadable line per branch; the `match` keeps the parser
            // shapes visually aligned and the surrounding outer match
            // already establishes the structure.
            #[allow(clippy::option_if_let_else)]
            let parser = match prop {
                LexUserType::String(s) => match string_format_constructor(s.format.as_deref()) {
                    Some(ctor) => format!("ctx.params.get(\"{key}\").and_then(|v| {ctor}(v).ok())"),
                    None => format!("ctx.params.get(\"{key}\").cloned()"),
                },
                LexUserType::Integer(_) => {
                    format!("ctx.params.get(\"{key}\").and_then(|v| v.parse::<i64>().ok())")
                }
                LexUserType::Boolean(_) => {
                    format!("ctx.params.get(\"{key}\").and_then(|v| v.parse::<bool>().ok())")
                }
                LexUserType::Array(arr) => match &*arr.items {
                    LexUserType::String(s) => {
                        match string_format_constructor(s.format.as_deref()) {
                            Some(ctor) => format!(
                                "ctx.params.get(\"{key}\").and_then(|v| v.split(',').map({ctor}).collect::<Result<Vec<_>, _>>().ok())"
                            ),
                            None => format!(
                                "Some(ctx.params.get(\"{key}\").map(|v| v.split(',').map(String::from).collect::<Vec<_>>()).unwrap_or_default())"
                            ),
                        }
                    }
                    _ => format!("ctx.params.get(\"{key}\").cloned().map(|_| Vec::new())"),
                },
                _ => format!("ctx.params.get(\"{key}\").cloned()"),
            };

            if is_required {
                // required fields get the bare value (Option is
                // unwrapped with a default-ish fallback); upstream
                // lexicon validation should have caught absence.
                writeln!(out, "        {field}: ({parser})?,").expect("infallible write to String");
            } else {
                writeln!(out, "        {field}: {parser},").expect("infallible write to String");
            }
        }

        out.push_str("    })\n");
        out.push_str("}\n\n");
    }

    /// Emit a helper that converts `&Params` into a `QueryParams` map.
    ///
    /// Skips fields whose value is `None` so `skip_serializing_if =
    /// "Option::is_none"` semantics carry through to the wire.
    fn generate_to_query_params(out: &mut String, params: &LexXrpcParameters) {
        out.push_str("fn to_query_params(p: &Params) -> proto_blue_xrpc::QueryParams {\n");
        out.push_str("    let mut qp = proto_blue_xrpc::QueryParams::new();\n");

        let mut prop_names: Vec<&String> = params.properties.keys().collect();
        prop_names.sort();
        let required: BTreeSet<&str> = params.required.iter().map(String::as_str).collect();

        for prop_name in prop_names {
            let prop = &params.properties[prop_name];
            let field = to_snake_case(prop_name);
            let is_required = required.contains(prop_name.as_str());
            let key = prop_name;

            // Use `ToString::to_string` (Display) on the field so the same
            // template emission works for plain `String` (Display = identity)
            // and any of the validated `proto_blue_syntax::*` newtypes
            // (Display = the inner string). No special-casing per format.
            let conv = match prop {
                LexUserType::String(_) => {
                    "proto_blue_xrpc::QueryValue::String(v.to_string())".to_string()
                }
                LexUserType::Integer(_) => {
                    format!("proto_blue_xrpc::QueryValue::Integer({})", "*v")
                }
                LexUserType::Boolean(_) => {
                    format!("proto_blue_xrpc::QueryValue::Boolean({})", "*v")
                }
                LexUserType::Array(arr) => match &*arr.items {
                    LexUserType::String(_) => {
                        "proto_blue_xrpc::QueryValue::Array(v.iter().map(|x| proto_blue_xrpc::QueryValue::String(x.to_string())).collect())".to_string()
                    }
                    LexUserType::Integer(_) => {
                        "proto_blue_xrpc::QueryValue::Array(v.iter().map(|x| proto_blue_xrpc::QueryValue::Integer(*x)).collect())".to_string()
                    }
                    _ => {
                        "proto_blue_xrpc::QueryValue::String(String::new())".to_string()
                    }
                },
                _ => "proto_blue_xrpc::QueryValue::String(String::new())".to_string(),
            };

            if is_required {
                writeln!(
                    out,
                    "    {{ let v = &p.{field}; qp.insert(\"{key}\".to_string(), {conv}); }}"
                )
                .expect("infallible write to String");
            } else {
                writeln!(
                    out,
                    "    if let Some(v) = &p.{field} {{ qp.insert(\"{key}\".to_string(), {conv}); }}"
                )
                .expect("infallible write to String");
            }
        }

        out.push_str("    qp\n");
        out.push_str("}\n\n");
    }

    /// Generate a subscription.
    fn generate_subscription(
        out: &mut String,
        nsid: &str,
        _type_name: &str,
        sub: &LexXrpcSubscription,
    ) {
        let has_params = sub
            .parameters
            .as_ref()
            .is_some_and(|p| !p.properties.is_empty());
        // Post-parity-refactor (#46): `LexXrpcSubscription.message` now
        // carries a required `LexRefUnion` schema rather than the old
        // optional `LexXrpcBody`. The presence of a message is
        // determined solely by `sub.message.is_some()`.
        let has_message = sub.message.is_some();

        if has_params || has_message {
            if let Some(desc) = &sub.description {
                writeln!(out, "/// {}", escape_doc_text(desc)).expect("infallible write to String");
            }
            writeln!(out, "/// XRPC Subscription: {nsid}").expect("infallible write to String");
        }

        if let Some(params) = &sub.parameters
            && !params.properties.is_empty()
        {
            Self::generate_params(out, nsid, params);
        }

        if let Some(msg) = &sub.message {
            // Wrap the `LexRefUnion` back into a `LexUserType::Union`
            // so `generate_body_schema`'s existing union-codegen path
            // (tagged enum of boxed variants) can handle it unchanged.
            let union_def = LexUserType::Union(msg.schema.clone());
            Self::generate_body_schema(out, nsid, "Message", &union_def);
        }
    }

    /// Generate a Params struct from XRPC parameters.
    fn generate_params(out: &mut String, _nsid: &str, params: &LexXrpcParameters) {
        out.push_str("#[derive(Debug, Clone, Serialize, Deserialize)]\n");
        out.push_str("#[serde(rename_all = \"camelCase\")]\n");
        out.push_str("pub struct Params {\n");

        let mut prop_names: Vec<&String> = params.properties.keys().collect();
        prop_names.sort();
        let required: BTreeSet<&str> = params.required.iter().map(String::as_str).collect();
        let mut seen_idents: std::collections::HashSet<String> = std::collections::HashSet::new();

        for prop_name in prop_names {
            let prop_type = &params.properties[prop_name];
            let is_required = required.contains(prop_name.as_str());
            let raw_rust_name = to_snake_case(prop_name);
            let rust_name = disambiguate(&mut seen_idents, raw_rust_name.clone());
            let was_disambiguated = rust_name != raw_rust_name;
            let rust_type = Self::param_type_to_rust(prop_type);

            if was_disambiguated {
                writeln!(
                    out,
                    "    /// Renamed from `{prop_name}` to avoid a Rust identifier collision with a sibling param."
                )
                .expect("infallible write to String");
            }

            let needs_rename = rust_name != *prop_name && to_camel_case(&rust_name) != *prop_name;
            if needs_rename {
                writeln!(out, "    #[serde(rename = \"{prop_name}\")]")
                    .expect("infallible write to String");
            }

            if is_required {
                writeln!(out, "    pub {rust_name}: {rust_type},")
                    .expect("infallible write to String");
            } else {
                out.push_str("    #[serde(skip_serializing_if = \"Option::is_none\")]\n");
                writeln!(out, "    pub {rust_name}: Option<{rust_type}>,")
                    .expect("infallible write to String");
            }
        }

        out.push_str("}\n\n");
    }

    /// Generate a struct from a body schema (input/output/message).
    fn generate_body_schema(out: &mut String, nsid: &str, name: &str, schema: &LexUserType) {
        match schema {
            LexUserType::Object(obj) => {
                Self::generate_object(out, nsid, name, obj, false);
            }
            LexUserType::Ref(r) => {
                let rust_type = Self::ref_to_rust(nsid, &r.ref_target);
                writeln!(out, "pub type {name} = {rust_type};")
                    .expect("infallible write to String");
                out.push('\n');
            }
            LexUserType::Union(union_def) => {
                Self::generate_union(out, nsid, name, union_def);
            }
            _ => {}
        }
    }

    /// Generate a Rust enum for a string with enum values.
    fn generate_string_enum(
        out: &mut String,
        type_name: &str,
        values: &[String],
        description: Option<&str>,
    ) {
        if let Some(desc) = description {
            writeln!(out, "/// {}", escape_doc_text(desc)).expect("infallible write to String");
        }
        out.push_str("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n");
        writeln!(out, "pub enum {type_name} {{").expect("infallible write to String");

        let mut seen_variants: std::collections::HashSet<String> = std::collections::HashSet::new();
        for value in values {
            let raw_variant = to_pascal_case(value);
            let variant_name = disambiguate(&mut seen_variants, raw_variant.clone());
            let was_disambiguated = variant_name != raw_variant;

            if was_disambiguated {
                writeln!(
                    out,
                    "    /// Renamed from `{value}` to avoid a Rust variant collision with a sibling."
                )
                .expect("infallible write to String");
            }
            // serde rename when the wire form differs from the chosen
            // variant identifier (always the case after disambiguation).
            if variant_name != *value {
                writeln!(out, "    #[serde(rename = \"{value}\")]")
                    .expect("infallible write to String");
            }
            writeln!(out, "    {variant_name},").expect("infallible write to String");
        }

        out.push_str("}\n\n");
    }

    /// Generate known values as a type alias + constants.
    fn generate_known_values(
        out: &mut String,
        type_name: &str,
        values: &[String],
        description: Option<&str>,
    ) {
        if let Some(desc) = description {
            writeln!(out, "/// {}", escape_doc_text(desc)).expect("infallible write to String");
        }
        // Known values allow extension, so use String with named constants.
        writeln!(out, "pub type {type_name} = String;").expect("infallible write to String");

        // Values may be fully-qualified (e.g. "app.bsky.graph.defs#modlist")
        // — extract just the fragment after '#' if present for the const name.
        //
        // The constant identifier joins the type name and the fragment
        // in pure SCREAMING_SNAKE form (both pieces go through
        // `to_screaming_snake`) so the result is valid per Rust's
        // `non_upper_case_globals` lint — e.g. `ReasonType` +
        // `reason-violence-other` → `REASON_TYPE_REASON_VIOLENCE_OTHER`.
        let type_prefix = to_screaming_snake(type_name);
        let mut seen = BTreeSet::new();
        for value in values {
            let short = value
                .rsplit_once('#')
                .map_or(value.as_str(), |(_, frag)| frag);
            let const_name = to_screaming_snake(short);
            let full_name = format!("{type_prefix}_{const_name}");
            if seen.insert(full_name.clone()) {
                writeln!(out, "pub const {full_name}: &str = \"{value}\";")
                    .expect("infallible write to String");
            }
        }
        out.push('\n');
    }

    /// Generate a union enum.
    fn generate_union(out: &mut String, nsid: &str, type_name: &str, union_def: &LexRefUnion) {
        if let Some(desc) = &union_def.description {
            writeln!(out, "/// {}", escape_doc_text(desc)).expect("infallible write to String");
        }
        out.push_str("#[derive(Debug, Clone, Serialize, Deserialize)]\n");
        out.push_str("#[serde(tag = \"$type\")]\n");
        writeln!(out, "pub enum {type_name} {{").expect("infallible write to String");

        let mut seen_variants: std::collections::HashSet<String> = std::collections::HashSet::new();
        // Open unions also emit an `Other` variant below; reserve so a real
        // ref whose variant happens to be `Other` doesn't collide with it.
        if union_def.closed != Some(true) {
            seen_variants.insert("Other".to_string());
        }
        for ref_str in &union_def.refs {
            let (ref_nsid, ref_def) = parse_ref(nsid, ref_str);
            let raw_variant = ref_to_variant_name(&ref_nsid, &ref_def);
            let variant_name = disambiguate(&mut seen_variants, raw_variant.clone());
            let was_disambiguated = variant_name != raw_variant;
            let rust_type = Self::ref_to_rust(nsid, ref_str);
            let full_ref = if ref_def == "main" {
                ref_nsid.clone()
            } else {
                format!("{ref_nsid}#{ref_def}")
            };
            if was_disambiguated {
                writeln!(
                    out,
                    "    /// Renamed from `{raw_variant}` to avoid a Rust variant collision with a sibling."
                )
                .expect("infallible write to String");
            }
            writeln!(out, "    #[serde(rename = \"{full_ref}\")]")
                .expect("infallible write to String");
            writeln!(out, "    {variant_name}(Box<{rust_type}>),")
                .expect("infallible write to String");
        }

        // Open unions allow unknown types
        if union_def.closed != Some(true) {
            out.push_str("    #[serde(other)]\n");
            out.push_str("    Other,\n");
        }

        out.push_str("}\n\n");
    }

    /// Convert a Lexicon type to a Rust type string.
    ///
    /// String fields with a recognised `format` map to validated newtypes
    /// from `proto_blue_syntax` so the type system encodes the on-the-wire
    /// invariant (a DID-typed field really is a DID, etc.). `blob` maps to
    /// `proto_blue_lex_data::BlobRef` (the enum over typed + legacy forms
    /// from #32); `cid-link` maps to `proto_blue_lex_data::Cid`.
    fn type_to_rust(nsid: &str, ty: &LexUserType) -> String {
        match ty {
            LexUserType::String(s) => string_format_to_rust(s.format.as_deref()).to_string(),
            LexUserType::Integer(_) => "i64".to_string(),
            LexUserType::Boolean(_) => "bool".to_string(),
            LexUserType::Bytes(_) => "Vec<u8>".to_string(),
            LexUserType::CidLink(_) => "proto_blue_lex_data::Cid".to_string(),
            LexUserType::Blob(_) => "proto_blue_lex_data::BlobRef".to_string(),
            LexUserType::Array(arr) => {
                let inner = Self::type_to_rust(nsid, &arr.items);
                format!("Vec<{inner}>")
            }
            LexUserType::Ref(r) => Self::ref_to_rust(nsid, &r.ref_target),
            // `Unknown`, `Union` (when not synthesised inline), and any
            // future variant the lexicon grammar grows fall back to an
            // opaque JSON value. Collapsed via the wildcard so the three
            // identical bodies don't repeat.
            _ => "serde_json::Value".to_string(),
        }
    }

    /// Convert a param type to Rust.
    ///
    /// Mirrors `type_to_rust`'s `format`-aware mapping for `LexString`:
    /// string params with a recognised `format` are exposed as the
    /// validated `proto_blue_syntax` newtype rather than a bare `String`.
    /// The codegen-emitted `to_query_params` / `params_from_ctx` helpers
    /// pair this with `Display`-based serialisation and the syntax
    /// crate's `::new(&str) -> Result<_, _>` constructor for parsing,
    /// so wire-string ↔ typed-newtype round-trips work for any caller.
    fn param_type_to_rust(ty: &LexUserType) -> String {
        match ty {
            LexUserType::String(s) => string_format_to_rust(s.format.as_deref()).to_string(),
            LexUserType::Integer(_) => "i64".to_string(),
            LexUserType::Boolean(_) => "bool".to_string(),
            LexUserType::Array(arr) => {
                let inner = Self::param_type_to_rust(&arr.items);
                format!("Vec<{inner}>")
            }
            // `Unknown` and any other variant fall back to a plain `String`
            // because query params are wire-string already. Collapsed via
            // the wildcard so the two identical bodies don't repeat.
            _ => "String".to_string(),
        }
    }

    /// Convert a ref target to a Rust type path.
    fn ref_to_rust(current_nsid: &str, ref_target: &str) -> String {
        let (ref_nsid, ref_def) = parse_ref(current_nsid, ref_target);

        if ref_nsid == current_nsid {
            // Local reference within the same file
            def_name_to_type(&ref_def)
        } else {
            // Cross-module reference. NSID segments are usually
            // lowercase but the final method-name segment is often
            // camelCase (`getSession`, `createRecord`). The module
            // declaration in mod.rs renames those to snake_case via
            // `#[path]`, so cross-refs must use the snake form too.
            let parts: Vec<&str> = ref_nsid.split('.').collect();
            let module_path = parts
                .iter()
                .map(|p| sanitize_ident(&to_snake_case(p)))
                .collect::<Vec<_>>()
                .join("::");
            let type_name = def_name_to_type(&ref_def);
            format!("crate::{module_path}::{type_name}")
        }
    }
}

/// Source-code expression for the validating `::new(&str) -> Result<_, _>`
/// constructor of the newtype `string_format_to_rust` maps a given format
/// to. Returns `None` when the format is unmapped or absent — i.e. when
/// the param's Rust type is a plain `String`.
///
/// Used by the param-helper code paths (`to_query_params`,
/// `params_from_ctx`) to parse query-string values into the typed newtype
/// at the call boundary.
fn string_format_constructor(format: Option<&str>) -> Option<&'static str> {
    Some(match format {
        Some("did") => "proto_blue_syntax::Did::new",
        Some("handle") => "proto_blue_syntax::Handle::new",
        Some("at-identifier") => "proto_blue_syntax::AtIdentifier::new",
        Some("nsid") => "proto_blue_syntax::Nsid::new",
        Some("at-uri") => "proto_blue_syntax::AtUri::new",
        Some("tid") => "proto_blue_syntax::Tid::new",
        Some("record-key") => "proto_blue_syntax::RecordKey::new",
        Some("datetime") => "proto_blue_syntax::Datetime::new",
        _ => return None,
    })
}

/// Map a Lexicon `string` `format` value to a Rust type path.
///
/// Recognised formats use the validated newtypes from `proto_blue_syntax`
/// so a typed-string field's invariant (it really is a DID, NSID, etc.)
/// is enforced at the type system rather than left as runtime parsing
/// at every consumer. Unrecognised or absent formats fall back to
/// `String`.
///
/// Notes:
/// - `cid` falls back to `String` here because `LexUserType::CidLink` is
///   the lexicon's intended way to type a CID-as-link (the `cid-link`
///   user type), and `format: cid` on a plain string is rare and
///   semantically distinct (raw CID string, not a CBOR tag-42 link).
/// - `language` and `uri` keep `String` because their newtypes in
///   `proto_blue_syntax` don't currently impl serde's `Serialize` /
///   `Deserialize`, so emitting them in `#[derive(Serialize, Deserialize)]`
///   structs wouldn't compile. Promote in a follow-up once those traits land.
fn string_format_to_rust(format: Option<&str>) -> &'static str {
    match format {
        Some("did") => "proto_blue_syntax::Did",
        Some("handle") => "proto_blue_syntax::Handle",
        Some("at-identifier") => "proto_blue_syntax::AtIdentifier",
        Some("nsid") => "proto_blue_syntax::Nsid",
        Some("at-uri") => "proto_blue_syntax::AtUri",
        Some("tid") => "proto_blue_syntax::Tid",
        Some("record-key") => "proto_blue_syntax::RecordKey",
        Some("datetime") => "proto_blue_syntax::Datetime",
        // `cid` / `language` / `uri` and any other format: see fn doc.
        _ => "String",
    }
}

/// Join a parent directory with a child segment, used to look up
/// whether a child has further sub-children in `mod_tree`.
fn join_dir(dir: &str, child: &str) -> String {
    if dir.is_empty() {
        child.to_string()
    } else {
        format!("{dir}/{child}")
    }
}

