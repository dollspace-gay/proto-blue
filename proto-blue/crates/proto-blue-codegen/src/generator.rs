    /// Regression test for #25: lexicon descriptions with internal `\n`
    /// must emit a `///` continuation on each subsequent line so the
    /// wrapping `format!("/// {}\n", escape_doc_text(desc))` at the call
    /// site produces valid rustdoc rather than bare code.
    #[test]
    fn escape_doc_text_inserts_continuation_on_newlines() {
        let escaped = escape_doc_text("First line.\nSecond line.");
        assert_eq!(escaped, "First line.\n/// Second line.");

        // Multi-paragraph (blank line between) survives — the empty
        // continuation line is still a valid (empty) rustdoc line.
        let multi = escape_doc_text("Para one.\n\nPara two.");
        assert_eq!(multi, "Para one.\n/// \n/// Para two.");

        // Single-line descriptions are passed through unchanged (modulo
        // any URL wrapping, which is the helper's other job).
        let plain = escape_doc_text("No newlines here.");
        assert_eq!(plain, "No newlines here.");
    }
