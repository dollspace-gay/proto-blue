/// Rewrite a lexicon description for emission as a rustdoc comment.
///
/// Two transformations:
///
/// 1. **Bare `http(s)` URLs** are wrapped in `<…>`. Rustdoc requires
///    URLs to be in angle brackets or backticks so they render as
///    automatic links, and lints bare URLs at `-D warnings`.
///    URLs already inside `<...>` in the source are passed through
///    unchanged so we don't end up with `<<url>>`.
///
/// 2. **Internal newlines** become `\n/// ` so a multi-line lexicon
///    description like `"First line.\nSecond line."` survives
///    embedding as `/// {desc}\n` without breaking rustc's parser.
///    Without this, the second line would be emitted as bare code
///    and rustc would fail with `error: expected one of '!' or '::'`
///    on whatever the description happens to start with (#25).
fn escape_doc_text(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out = String::with_capacity(s.len());
    let mut i = 0;
    while i < bytes.len() {
        let rest = &s[i..];
        let scheme_len = if rest.starts_with("https://") {
            Some(8)
        } else if rest.starts_with("http://") {
            Some(7)
        } else {
            None
        };
        if let Some(n) = scheme_len {
            // Don't re-wrap a URL already inside `<...>` from the
            // source description.
            let already_wrapped = out.ends_with('<');
            let url_start = i;
            let mut url_end = i + n;
            while url_end < bytes.len() {
                let c = bytes[url_end];
                // Stop at whitespace or trailing punctuation that
                // typically terminates a URL in prose. Period,
                // comma, semicolon, colon, close-paren/bracket/brace
                // are the common cases; keep `#` and `?` in since
                // they're valid URL-internal chars.
                if c.is_ascii_whitespace() || matches!(c, b'<' | b'>') {
                    break;
                }
                url_end += 1;
            }
            // Trim trailing sentence punctuation off the URL.
            while url_end > url_start + n {
                let last = bytes[url_end - 1];
                if matches!(
                    last,
                    b'.' | b',' | b';' | b':' | b')' | b']' | b'}' | b'!' | b'?'
                ) {
                    url_end -= 1;
                } else {
                    break;
                }
            }
            if already_wrapped {
                out.push_str(&s[url_start..url_end]);
            } else {
                out.push('<');
                out.push_str(&s[url_start..url_end]);
                out.push('>');
            }
            i = url_end;
        } else {
            // Copy one char at a time; we can't rely on byte indexing
            // for multibyte chars, so advance by the char's utf8 len.
            let ch = rest.chars().next().unwrap();
            if ch == '\n' {
                // Continuation: every internal newline gets a `/// `
                // prefix on the next line so the wrapping `format!("/// {}\n", ...)`
                // at the call sites produces valid rustdoc.
                out.push_str("\n/// ");
            } else {
                out.push(ch);
            }
            i += ch.len_utf8();
        }
    }
    out
}

/// - `"#defName"` -> (`current_nsid`, `defName`)
/// - `"some.nsid#defName"` -> (`some.nsid`, `defName`)
/// - `"some.nsid"` -> (`some.nsid`, `main`)
//
// `option_if_let_else` would collapse the if-let / else-if-let / else
// chain into a nested `map_or_else` pair, which obscures the three-case
// structure (leading-`#`, embedded-`#`, no-`#`). Per-site judgment: keep
// the if-let cascade and silence the lint.
#[allow(clippy::option_if_let_else)]
fn parse_ref(current_nsid: &str, ref_str: &str) -> (String, String) {
    if let Some(suffix) = ref_str.strip_prefix('#') {
        (current_nsid.to_string(), suffix.to_string())
    } else if let Some(pos) = ref_str.find('#') {
        (ref_str[..pos].to_string(), ref_str[pos + 1..].to_string())
    } else {
        (ref_str.to_string(), "main".to_string())
    }
}

/// Convert a def name to a Rust type name (`PascalCase`).
/// Avoids conflicts with standard library types.
fn def_name_to_type(def_name: &str) -> String {
    if def_name == "main" {
        "Main".to_string()
    } else {
        let name = to_pascal_case(def_name);
        sanitize_type_name(&name)
    }
}

/// Ensure a type name doesn't conflict with standard library types.
fn sanitize_type_name(name: &str) -> String {
    match name {
        "Option" => "LexOption".to_string(),
        "Result" => "LexResult".to_string(),
        "Error" => "LexError".to_string(),
        "Box" => "LexBox".to_string(),
        "String" => "LexString".to_string(),
        "Vec" => "LexVec".to_string(),
        _ => name.to_string(),
    }
}

/// Generate a variant name for a union member.
///
/// Uses every NSID segment after the first (the top-level reverse-TLD
/// like `app` / `com`) to guarantee uniqueness across the 322-schema
/// registry. Previously only the last two segments were used, which
/// collided for cross-namespace names like
/// `app.bsky.feed.defs#postView` vs `app.bsky.unspecced.defs#postView`
/// (both would produce `DefsPostView`). Now they become
/// `BskyFeedDefsPostView` and `BskyUnspeccedDefsPostView` respectively.
fn ref_to_variant_name(nsid: &str, def_name: &str) -> String {
    let parts: Vec<&str> = nsid.split('.').collect();
    let suffix = if def_name == "main" {
        String::new()
    } else {
        to_pascal_case(def_name)
    };

    // Skip the reverse-TLD root (e.g. `app`, `com`) when the path has
    // enough depth to distinguish meaningfully without it; otherwise
    // fall back to the whole path.
    let ns_segments: Vec<String> = if parts.len() > 2 {
        parts[1..].iter().map(|p| to_pascal_case(p)).collect()
    } else {
        parts.iter().map(|p| to_pascal_case(p)).collect()
    };
    let ns: String = ns_segments.concat();

    format!("{ns}{suffix}")
}

/// Convert a string to `PascalCase`.
fn to_pascal_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize_next = true;

    for ch in s.chars() {
        if !ch.is_ascii_alphanumeric() {
            capitalize_next = true;
        } else if capitalize_next {
            result.push(ch.to_ascii_uppercase());
            capitalize_next = false;
        } else {
            result.push(ch);
        }
    }

    // Ensure it starts with uppercase
    if let Some(first) = result.chars().next() {
        if first.is_ascii_digit() {
            result = format!("V{result}");
        }
    }

    result
}

/// Convert a string to `snake_case`.
fn to_snake_case(s: &str) -> String {
    let mut result = String::new();
    let mut prev_was_upper = false;

    for (i, ch) in s.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 && !prev_was_upper {
                result.push('_');
            }
            result.push(ch.to_ascii_lowercase());
            prev_was_upper = true;
        } else if ch == '-' || ch == '.' || ch == '#' {
            result.push('_');
            prev_was_upper = false;
        } else if !ch.is_ascii_alphanumeric() && ch != '_' {
            // Strip non-alphanumeric chars like '!'
            prev_was_upper = false;
        } else {
            prev_was_upper = false;
            result.push(ch);
        }
    }

    sanitize_ident(&result)
}

/// Convert `snake_case` back to `camelCase` for comparison.
fn to_camel_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize_next = false;

    for ch in s.chars() {
        if ch == '_' {
            capitalize_next = true;
        } else if capitalize_next {
            result.push(ch.to_ascii_uppercase());
            capitalize_next = false;
        } else {
            result.push(ch);
        }
    }
    result
}

/// Convert a string to `SCREAMING_SNAKE_CASE`.
fn to_screaming_snake(s: &str) -> String {
    let snake = to_snake_case(s);
    snake.to_ascii_uppercase()
}

/// Sanitize a Rust identifier, escaping keywords.
///
/// Covers:
/// - Rust 2018/2021 strict keywords
/// - Rust 2024 keywords (`gen`, `try`)
/// - Reserved-for-future keywords (`priv`, `abstract`, `become`, `box`, `do`,
///   `final`, `macro`, `override`, `typeof`, `virtual`, `yield`)
/// - Weak/contextual keywords that are safer to escape than gamble on
///   future hard reservations (`union`, `dyn` was promoted in 2018, `async`
///   / `await` were promoted in 2018; `gen` / `try` were promoted in 2024
///   per <https://doc.rust-lang.org/reference/keywords.html>).
///
/// Anything not in the list passes through unmodified.
fn sanitize_ident(s: &str) -> String {
    let s = s.replace('-', "_");
    match s.as_str() {
        // 2015/2018/2021 strict
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern"
        | "false" | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod"
        | "move" | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct"
        | "super" | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while"
        // promoted in 2018
        | "async" | "await" | "dyn"
        // promoted in 2024
        | "gen" | "try"
        // reserved-for-future
        | "abstract" | "become" | "box" | "do" | "final" | "macro" | "override" | "priv"
        | "typeof" | "unsized" | "virtual" | "yield"
        // weak / future-reservation candidates — safer to escape than gamble
        | "union" => format!("r#{s}"),
        _ => s,
    }
}

/// Disambiguate `candidate` against already-emitted identifiers.
///
/// If `candidate` is unique in `seen`, inserts and returns it unchanged.
/// Otherwise appends `_2`, `_3`, ... until a free form is found, inserts
/// the resulting name, and returns it.
///
/// Used by the field/variant emission sites to keep generated structs
/// and enums valid Rust even when two source names sanitize to the same
/// identifier (e.g. `myField` and `my_field` both → `my_field`, or
/// `type` and a literal `r#type` field both → `r#type`). Each colliding
/// field still serdes via its original wire name through a `serde(rename)`
/// attribute the caller emits.
fn disambiguate(seen: &mut std::collections::HashSet<String>, candidate: String) -> String {
    if seen.insert(candidate.clone()) {
        return candidate;
    }
    let mut n: u32 = 2;
    loop {
        let alt = format!("{candidate}_{n}");
        if seen.insert(alt.clone()) {
            return alt;
        }
        n = n
            .checked_add(1)
            .expect("identifier disambiguation counter overflow (>4 billion siblings)");
    }
}

